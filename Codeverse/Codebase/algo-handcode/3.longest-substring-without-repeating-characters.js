/**
 * @param {string} s
 * @return {number}
 */
var lengthOfLongestSubstring = function(s) {
    // abcabcbb
    let left = -1
    const map = new Map() // 记录 元素：最近一次的 index

    let res = 0
    for (let i = 0; i < s.length; i++) {
      if (map.has(s[i])) {
        left = Math.max(map.get(s[i]), left)  // 防止左指针向左
      }
      res = Math.max(res, i - left)
      map.set(s[i], i)
    }

    return res
};
