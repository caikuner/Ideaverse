var a = 0,
  b = 0;
function A(a) {
  A = function (b) {  // 闭包A 记住了自己词法作用域的环境，变量a = 2
    console.log(a+b++);  // a+b, b++
  };
  console.log(a++); // a=1, 然后+1
}
A(1); // 1
A(2);  //4, a+b=2+2=4, b++

console.log(a, b) // 0,0

// 问题：闭包 A 记住的是之前运行时的 a=1，还是后面+1 后的 2？⚠️
// 是 2. 闭包是记住了他的词法环境上的局部变量，而不是拿了一份快照。后期修改仍然能访问到